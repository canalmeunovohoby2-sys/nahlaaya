create extension if not exists pgcrypto;

create table if not exists public.products (
  id text primary key,
  slug text not null unique,
  name text not null,
  brand text not null,
  volume_ml integer not null check (volume_ml > 0),
  concentration text not null,
  pix_price_cents bigint not null check (pix_price_cents >= 0),
  debit_price_cents bigint not null check (debit_price_cents >= 0),
  installment_total_cents bigint not null check (installment_total_cents >= 0),
  stock integer not null default 0 check (stock >= 0),
  category text,
  images jsonb not null default '[]'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  cpf text not null,
  email text not null,
  phone text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint customers_cpf_unique unique (cpf),
  constraint customers_email_unique unique (email)
);

create table if not exists public.addresses (
  id bigint generated by default as identity primary key,
  customer_id bigint not null references public.customers(id),
  cep text not null,
  street text not null,
  number text not null,
  complement text not null default '',
  neighborhood text not null,
  city text not null,
  state text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  customer_id bigint not null references public.customers(id),
  address_id bigint not null references public.addresses(id),
  payment_method text not null check (payment_method in ('pix', 'debit', 'credit')),
  subtotal_pix_cents bigint not null check (subtotal_pix_cents >= 0),
  subtotal_debit_cents bigint not null check (subtotal_debit_cents >= 0),
  installment_total_cents bigint not null check (installment_total_cents >= 0),
  selected_total_cents bigint not null check (selected_total_cents >= 0),
  shipping_total_cents bigint,
  total_cents bigint not null check (total_cents >= 0),
  payment_status text not null default 'pending'
    check (payment_status in ('pending', 'paid', 'cancelled', 'failed')),
  payment_failure_terminal boolean not null default false,
  delivery_status text not null default 'pending'
    check (delivery_status in ('pending', 'preparing', 'shipped', 'delivered', 'cancelled')),
  payment_provider text,
  payment_reference text,
  stock_reserved_at timestamptz,
  reservation_expires_at timestamptz,
  stock_released_at timestamptz,
  stock_deducted_at timestamptz,
  paid_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint orders_failure_terminal_check
    check ((payment_status = 'failed') = payment_failure_terminal),
  constraint orders_stock_release_check
    check (stock_released_at is null or stock_reserved_at is not null)
);

create unique index if not exists orders_payment_reference_unique
  on public.orders(payment_reference)
  where payment_reference is not null;

create index if not exists orders_payment_status_idx on public.orders(payment_status);
create index if not exists orders_delivery_status_idx on public.orders(delivery_status);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists orders_stock_reservation_idx
  on public.orders (payment_status, reservation_expires_at)
  where stock_reserved_at is not null and stock_released_at is null;

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  product_name text not null,
  brand text not null,
  quantity integer not null check (quantity > 0),
  unit_pix_cents bigint not null check (unit_pix_cents >= 0),
  unit_debit_cents bigint not null check (unit_debit_cents >= 0),
  unit_installment_cents bigint not null check (unit_installment_cents >= 0),
  line_pix_cents bigint not null check (line_pix_cents >= 0),
  line_debit_cents bigint not null check (line_debit_cents >= 0),
  line_installment_cents bigint not null check (line_installment_cents >= 0)
);

create index if not exists order_items_order_idx on public.order_items(order_id);

create table if not exists public.order_payment_events (
  id uuid primary key default gen_random_uuid(),
  order_id bigint not null references public.orders(id) on delete cascade,
  provider text not null,
  provider_event_id text not null,
  status text not null,
  amount_cents bigint,
  payload jsonb,
  created_at timestamptz not null default now(),
  constraint order_payment_event_unique unique (provider_event_id)
);

create table if not exists public.admin_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin')),
  created_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch_updated_at on public.products;
create trigger products_touch_updated_at
before update on public.products
for each row execute function public.touch_updated_at();

drop trigger if exists customers_touch_updated_at on public.customers;
create trigger customers_touch_updated_at
before update on public.customers
for each row execute function public.touch_updated_at();

drop trigger if exists orders_touch_updated_at on public.orders;
create trigger orders_touch_updated_at
before update on public.orders
for each row execute function public.touch_updated_at();

create or replace function public.release_order_stock_on_cancel()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item public.order_items%rowtype;
begin
  if new.payment_status in ('cancelled', 'failed')
     and old.payment_status = 'pending'
     and (new.payment_status = 'cancelled' or new.payment_failure_terminal)
     and new.stock_reserved_at is not null
     and new.stock_released_at is null then
    for v_item in
      select * from public.order_items where order_id = new.id
    loop
      update public.products
      set stock = stock + v_item.quantity
      where id = v_item.product_id;
    end loop;

    new.stock_released_at := now();
  end if;

  return new;
end;
$$;

revoke all on function public.release_order_stock_on_cancel() from public, anon, authenticated;
grant execute on function public.release_order_stock_on_cancel() to service_role;

drop trigger if exists orders_release_stock_on_cancel on public.orders;
create trigger orders_release_stock_on_cancel
before update of payment_status on public.orders
for each row execute function public.release_order_stock_on_cancel();

